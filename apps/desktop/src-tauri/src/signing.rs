//! Commit signing per identity (PLAN §4.4, §5.9): GPG key list for the identity editor, the
//! "Thử ký" probe, the SSH `allowed_signers` file the app generates from identities that sign
//! with SSH, and the verification status of a commit ("Đã xác minh" …).
//!
//! Signing itself is injected by the resolver ([`crate::accounts::identity_signing`]): every
//! command run as an identity with signing gets `commit.gpgsign=true`, `gpg.format` and
//! `user.signingkey` through `GIT_CONFIG_*`.

