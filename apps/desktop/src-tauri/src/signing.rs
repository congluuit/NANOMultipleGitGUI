async fn blocking<T: Send + 'static>(
    app: AppHandle,
    f: impl FnOnce(&AppState) -> AppResult<T> + Send + 'static,
) -> AppResult<T> {
    tauri::async_runtime::spawn_blocking(move || f(&app.state::<AppState>()))
        .await
        .map_err(|e| AppError::Internal(e.to_string()))?
}

/// `<app data>/allowed_signers` (temp dir when the runtime has no data dir, e.g. in tests).
pub fn allowed_signers_path(st: &AppState) -> PathBuf {
    st.accounts
        .data_dir
        .clone()
        .unwrap_or_else(|| std::env::temp_dir().join("nanomgg-test-data"))
        .join("allowed_signers")
}

/// Public key text for an SSH signing key reference: `key::<public key>`, a `.pub` file, or a
/// private key known to the app's key list (its stored public key) / with a `.pub` next to it.
pub fn ssh_public_key(st: &AppState, key_ref: &str) -> Option<String> {
    let key_ref = key_ref.trim();
    if let Some(literal) = key_ref.strip_prefix("key::") {
        return Some(literal.trim().to_owned());
    }
    let read = |p: &Path| {
        std::fs::read_to_string(p)
            .ok()
            .map(|s| s.trim().to_owned())
            .filter(|s| s.starts_with("ssh-") || s.starts_with("ecdsa-") || s.starts_with("sk-"))
    };
    if key_ref.ends_with(".pub")
        && let Some(k) = read(Path::new(key_ref))
    {
        return Some(k);
    }
    let private = key_ref.strip_suffix(".pub").unwrap_or(key_ref);
    let same = |a: &str| {
        a.replace('\\', "/")
            .eq_ignore_ascii_case(&private.replace('\\', "/"))
    };
    if let Ok(keys) = st.storage.ssh_keys(None)
        && let Some(k) = keys
            .into_iter()
            .find(|k| k.private_key_path.as_deref().is_some_and(same))
    {
        return Some(k.public_key);
    }
    read(Path::new(&format!("{private}.pub")))
}

/// Lines of the generated `allowed_signers`: every identity signing with SSH, then the user's
/// own `gpg.ssh.allowedSignersFile` (so verification keeps trusting what it trusted before).
pub fn allowed_signers_content(st: &AppState, identities: &[Identity]) -> String {
    let mut lines: Vec<String> = Vec::new();
    for i in identities
        .iter()
        .filter(|i| i.signing == SigningMethod::Ssh)
    {
        if let Some(key) = i
            .signing_key_ref
            .as_deref()
            .and_then(|r| ssh_public_key(st, r))
            && let Some(line) = allowed_signers_line(&i.email, &key)
            && !lines.contains(&line)
        {
            lines.push(line);
        }
    }
    let user_file = st
        .git
        .run_text(
            &std::env::temp_dir(),
            &AccountContext::default(),
            ["config", "--global", "--get", "gpg.ssh.allowedSignersFile"],
        )
        .ok()
        .filter(|p| !p.is_empty());
    if let Some(path) = user_file {
        let path = match path.strip_prefix("~/") {
            Some(rest) => std::env::var_os(if cfg!(windows) { "USERPROFILE" } else { "HOME" })
                .map(|h| PathBuf::from(h).join(rest))
                .unwrap_or_else(|| PathBuf::from(&path)),
            None => PathBuf::from(&path),
        };
        if let Ok(text) = std::fs::read_to_string(path) {
            lines.extend(
                text.lines()
                    .map(str::trim)
                    .filter(|l| !l.is_empty() && !l.starts_with('#'))
                    .map(str::to_owned),
            );
        }
    }
    let mut out =
        String::from("# Generated by NANOMultipleGitGUI from identities that sign with SSH.\n");
    for l in lines {
        out.push_str(&l);
        out.push('\n');
    }
    out
}

/// Rewrites the app's `allowed_signers` when its content changed; returns its path.
pub fn refresh_allowed_signers(st: &AppState) -> AppResult<PathBuf> {
    let identities = st.storage.identities(None).map_err(storage_err)?;
    let content = allowed_signers_content(st, &identities);
    let path = allowed_signers_path(st);
    if std::fs::read_to_string(&path).ok().as_deref() != Some(content.as_str()) {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| AppError::Internal(e.to_string()))?;
        }
        std::fs::write(&path, content).map_err(|e| AppError::Internal(e.to_string()))?;
    }
    Ok(path)
}

/// Signature of commit `oid` with verification (SSH through the app's `allowed_signers`).
pub(crate) fn commit_signature_impl(
    st: &AppState,
    repo_id: i64,
    oid: &str,
) -> AppResult<CommitSignature> {
    let root = repo_root(st, repo_id)?;
    let allowed = match refresh_allowed_signers(st) {
        Ok(p) => Some(p),
        Err(e) => {
            tracing::warn!(error = %e, "could not write allowed_signers");
            None
        }
    };
    let mut sig = signature::commit_signature(&st.git, &root, oid, allowed.as_deref())?;
    sig.message = sig
        .message
        .map(|m| nanomgg_logging::redact(&m).into_owned());
    Ok(sig)
}

/// Verification status of a commit's signature (lazy: the details panel asks only for signed
/// commits, see `CommitDetails.signature`).
#[tauri::command]
#[specta::specta]
pub async fn commit_signature(
    app: AppHandle,
    repo_id: i64,
    oid: String,
) -> AppResult<CommitSignature> {
    blocking(app, move |st| commit_signature_impl(st, repo_id, &oid)).await
}

/// GPG secret keys usable for signing, listed with the `gpg` git would run (`gpg.program`, the
/// one bundled with Git for Windows, or `gpg` on PATH). `notInstalled` when it cannot start.
#[tauri::command]
#[specta::specta]
pub async fn signing_gpg_keys(app: AppHandle) -> AppResult<GpgKeyList> {
    blocking(app, |st| {
        Ok(signature::list_gpg_secret_keys(
            &st.git,
            &std::env::temp_dir(),
        ))
    })
    .await
}

/// What to try in "Thử ký".
#[derive(Debug, Clone, Deserialize, Type)]
#[serde(rename_all = "camelCase")]
pub struct SigningProbe {
    /// Account whose identity / SSH passphrase prompt is used (optional).
    #[serde(default)]
    #[specta(optional)]
    pub account_id: Option<String>,
    pub signing: SigningMethod,
    pub signing_key_ref: String,
    /// Email the signature is for (SSH: checked against the key in a temporary allowed list).
    #[serde(default)]
    #[specta(optional)]
    pub email: Option<String>,
}

pub(crate) fn signing_test_impl(st: &AppState, probe: &SigningProbe) -> AppResult<SignTestResult> {
    let format = match probe.signing {
        SigningMethod::None => {
            return Err(AppError::InvalidInput(
                "choose GPG or SSH signing first".into(),
            ));
        }
        SigningMethod::Gpg => SigningFormat::OpenPgp,
        SigningMethod::Ssh => SigningFormat::Ssh,
    };
    let signing = signature::signing_for(format, &probe.signing_key_ref)
        .ok_or_else(|| AppError::InvalidInput("the signing key is empty".into()))?;
    let mut ctx = match &probe.account_id {
        Some(id) => accounts::context_for_account(st, id, None)?,
        None => AccountContext::default(),
    };
    if let Some(email) = probe.email.as_deref().filter(|e| !e.trim().is_empty()) {
        ctx.identity = Some(nanomgg_git_engine::Identity {
            name: ctx
                .identity
                .as_ref()
                .map_or_else(|| "NANOMultipleGitGUI".to_owned(), |i| i.name.clone()),
            email: email.trim().to_owned(),
        });
    }
    // SSH: verify against a one-line allowed list for this key, so "Verified" proves both
    // signing and the key/email pair.
    let scratch_allowed = match (format, probe.email.as_deref()) {
        (SigningFormat::Ssh, Some(email)) => ssh_public_key(st, &probe.signing_key_ref)
            .and_then(|k| allowed_signers_line(email, &k))
            .and_then(|line| {
                let p = std::env::temp_dir().join(format!(
                    "nanomgg-allowed-{}-{}",
                    std::process::id(),
                    std::time::SystemTime::now()
                        .duration_since(std::time::UNIX_EPOCH)
                        .map(|d| d.as_nanos())
                        .unwrap_or_default()
                ));
                std::fs::write(&p, format!("{line}\n")).ok().map(|_| p)
            }),
        _ => None,
    };
    let result = signature::test_signing(&st.git, &ctx, &signing, scratch_allowed.as_deref());
    if let Some(p) = &scratch_allowed {
        let _ = std::fs::remove_file(p);
    }
    let mut result = result?;
    result.message = result
        .message
        .map(|m| nanomgg_logging::redact(&m).into_owned());
    Ok(result)
}

/// "Thử ký": signs a throw-away commit with the given key (GPG: gpg-agent may ask for the
/// passphrase in its own window) and verifies it.
#[tauri::command]
#[specta::specta]
pub async fn signing_test(app: AppHandle, probe: SigningProbe) -> AppResult<SignTestResult> {
    blocking(app, move |st| signing_test_impl(st, &probe)).await
}

#[cfg(test)]
mod tests {
    use super::*;
    use nanomgg_storage::Storage;

    fn state() -> AppState {
        AppState::new(Storage::open_in_memory().unwrap())
    }

    #[test]
    fn public_keys_from_literal_and_pub_file() {
        let st = state();
        let dir = tempfile::tempdir().unwrap();
        let pub_file = dir.path().join("k.pub");
        std::fs::write(&pub_file, "ssh-ed25519 AAAAkey me@x\n").unwrap();
        assert_eq!(
            ssh_public_key(&st, &pub_file.to_string_lossy()).as_deref(),
            Some("ssh-ed25519 AAAAkey me@x")
        );
        // Private path → `.pub` next to it.
        let private = dir.path().join("k");
        assert_eq!(
            ssh_public_key(&st, &private.to_string_lossy()).as_deref(),
            Some("ssh-ed25519 AAAAkey me@x")
        );
        assert_eq!(
            ssh_public_key(&st, "key::ssh-ed25519 AAAAlit").as_deref(),
            Some("ssh-ed25519 AAAAlit")
        );
        assert_eq!(ssh_public_key(&st, "C:/nope/x.pub"), None);
    }

    #[test]
    fn allowed_signers_lists_ssh_identities_only() {
        let st = state();
        let dir = tempfile::tempdir().unwrap();
        let pub_file = dir.path().join("k.pub");
        std::fs::write(&pub_file, "ssh-ed25519 AAAAkey me@x\n").unwrap();
        let identity = |email: &str, signing, key: Option<String>| Identity {
            id: email.into(),
            account_id: "a".into(),
            name: "N".into(),
            email: email.into(),
            signing,
            signing_key_ref: key,
            is_default: false,
            created_at: 0,
        };
        let content = allowed_signers_content(
            &st,
            &[
                identity(
                    "ssh@x.dev",
                    SigningMethod::Ssh,
                    Some(pub_file.to_string_lossy().into_owned()),
                ),
                identity("gpg@x.dev", SigningMethod::Gpg, Some("ABCD".into())),
                identity("none@x.dev", SigningMethod::None, None),
            ],
        );
        assert!(content.contains("ssh@x.dev namespaces=\"git\" ssh-ed25519 AAAAkey"));
        assert!(!content.contains("gpg@x.dev") && !content.contains("none@x.dev"));
    }

    #[test]
    fn probe_rejects_no_signing() {
        let st = state();
        let err = signing_test_impl(
            &st,
            &SigningProbe {
                account_id: None,
                signing: SigningMethod::None,
                signing_key_ref: "x".into(),
                email: None,
            },
        )
        .unwrap_err();
        assert!(matches!(err, AppError::InvalidInput(_)));
    }
}
